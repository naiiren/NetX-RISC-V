#define N 4

int mult(int x, int y) {
    int result = 0;
    while (y > 0) {
        if (y & 1) {
            result += x;
        }
        x <<= 1;
        y >>= 1;
    }
    return result;
}

int main() {
    int a[N][N], b[N][N], c[N][N], d[N][N];
    a[0][0] = 1; a[0][1] = 2; a[0][2] = 3; a[0][3] = 4;
    a[1][0] = 5; a[1][1] = 4; a[1][2] = 3; a[1][3] = 2;
    a[2][0] = 1; a[2][1] = 0; a[2][2] = 1; a[2][3] = 0;
    a[3][0] = 2; a[3][1] = 3; a[3][2] = 4; a[3][3] = 5;

    b[0][0] = 5; b[0][1] = 4; b[0][2] = 3; b[0][3] = 2;
    b[1][0] = 1; b[1][1] = 0; b[1][2] = 1; b[1][3] = 0;
    b[2][0] = 2; b[2][1] = 3; b[2][2] = 4; b[2][3] = 5;
    b[3][0] = 1; b[3][1] = 2; b[3][2] = 3; b[3][3] = 4;

    for (int i = 0; i < N; ++i) {
        for (int j = 0; j < N; ++j) {
            c[i][j] = 0;
        }
    }

    for (int i = 0; i < N; ++i) {
        for (int j = 0; j < N; ++j) {
            for (int k = 0; k < N; ++k) {
                c[i][j] += mult(a[i][k], b[k][j]);
            }
        }
    }

    d[0][0] = 17;    d[0][1] = 21;   d[0][2] = 29;   d[0][3] = 33;
    d[1][0] = 37;    d[1][1] = 33;   d[1][2] = 37;   d[1][3] = 33;
    d[2][0] = 7;     d[2][1] = 7;    d[2][2] = 7;    d[2][3] = 7;
    d[3][0] = 26;    d[3][1] = 30;   d[3][2] = 40;   d[3][3] = 44;
       
    for (int i = 0 ; i < N; ++i) {
        for (int j = 0; j < N; ++j) {
            if (c[i][j] != d[i][j]) {
                return 0xDEADBEEF;
            }
        }
    }

    return 0x00C0FFEE;
}